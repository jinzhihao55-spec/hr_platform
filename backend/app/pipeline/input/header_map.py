def normalize(text: str | None) -> str:
    if text is None:
        return ""
    return re.sub(r"\s+", "", str(text))


def build_lookup(columns: list, mapping: dict) -> dict:
    """返回 {规范键: 原始列名}，仅含存在的列。"""
    norm_map = {normalize(k): v for k, v in mapping.items()}
    out = {}
    for col in columns:
        key = norm_map.get(normalize(col))
        if key and key not in out:
            out[key] = col
    return out
